// wrangler.jsonc + .prod/state.json -> wrangler.production.jsonc (gitignored).
// Usage: node scripts/render-wrangler.ts [--state path] [--out path] [--runs-enabled true|false] [--aud value]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse, type ParseError, printParseErrorCode } from "jsonc-parser";
import { PLACEHOLDERS, type ProdState, placeholderValues } from "./lib/prod-state.ts";

export function parseJsonc<T>(text: string, what: string): T {
  const errors: ParseError[] = [];
  const value = parse(text, errors, { allowTrailingComma: true }) as T;
  if (errors.length > 0) throw new Error(`${what}: ${errors.map((e) => printParseErrorCode(e.error)).join(", ")}`);
  return value;
}

/** Replace every __PL_*__ placeholder (string values anywhere in the config) from the production state. */
export function renderWrangler(configText: string, state: ProdState): string {
  const values = placeholderValues(state);
  const config = parseJsonc<Record<string, unknown>>(configText, "wrangler.jsonc");
  const visit = (v: unknown): unknown => {
    if (typeof v === "string") {
      let out = v;
      for (const p of PLACEHOLDERS) out = out.split(p).join(values[p]);
      return out;
    }
    if (Array.isArray(v)) return v.map(visit);
    if (v && typeof v === "object") return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, visit(x)]));
    return v;
  };
  const rendered = visit(config);
  return `// Generated by scripts/render-wrangler.ts from wrangler.jsonc and .prod/state.json. Do not edit or commit.\n${JSON.stringify(rendered, null, 2)}\n`;
}

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = process.cwd();
  const statePath = arg("--state") ?? join(root, ".prod", "state.json");
  const state = JSON.parse(readFileSync(statePath, "utf8")) as ProdState;
  const runs = arg("--runs-enabled");
  if (runs !== undefined) state.runs_enabled = runs === "true";
  const aud = arg("--aud");
  if (aud !== undefined) state.access.aud = aud;
  const out = arg("--out") ?? join(root, "wrangler.production.jsonc");
  writeFileSync(out, renderWrangler(readFileSync(join(root, "wrangler.jsonc"), "utf8"), state));
  console.log(`rendered ${out} (RUNS_ENABLED=${state.runs_enabled}, ACCESS_AUD=${state.access.aud === "pending" ? "pending" : "set"})`);
}
